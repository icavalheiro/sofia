// Generates src/Sofia.App/Theme/Icons.axaml from the Lucide glyph data installed for the Vue UI
// (src/Sofia.UI/node_modules/lucide-vue-next), so both UIs draw the same 24x24 stroke glyphs at 18px / stroke 1.75.
// Generator (spec 039): run `node tools/app/gen-icons.mjs` from the repository root after upgrading Lucide.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..')
const ui = join(root, 'src', 'Sofia.UI')
const lucideDir = join(ui, 'node_modules', 'lucide-vue-next')
const lucidePkg = JSON.parse(readFileSync(join(lucideDir, 'package.json'), 'utf8'))
const facade = readFileSync(join(ui, 'src', 'components', 'SofiaIcon.vue'), 'utf8')

// --- what the app needs: the semantic keys of SofiaIcon.vue and the Lucide component behind each one ------------

const importBlock = facade.slice(facade.indexOf("from 'lucide-vue-next'"), 0)
const importSource = facade.slice(facade.indexOf('import {'), facade.indexOf("} from 'lucide-vue-next'"))
const components = new Map()
for (const raw of importSource.replace('import {', '').split(',')) {
  const name = raw.trim()
  if (name) components.set(name, null)
}

const mapBlock = facade.slice(facade.indexOf('const ICONS'), facade.indexOf('const icon = computed'))
const keys = new Map()
for (const m of mapBlock.matchAll(/^\s{2}([A-Za-z0-9_]+):\s*([A-Za-z0-9_]+),?$/gm)) {
  keys.set(m[1], m[2])
}

// --- Lucide nodes -> one SVG path string ----------------------------------------------------------------

const kebab = (pascal) =>
  pascal
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .replace(/([a-zA-Z])(\d)/g, '$1-$2')
    .toLowerCase()

const attrMap = (text) => {
  const attrs = {}
  for (const m of text.matchAll(/([A-Za-z]+):\s*(?:"([^"]*)"|(-?[\d.]+))/g)) {
    attrs[m[1]] = m[2] !== undefined ? m[2] : Number(m[3])
  }
  return attrs
}

const num = (v, fallback = 0) => (v === undefined ? fallback : Number(v))

const toPath = (tag, a) => {
  switch (tag) {
    case 'path':
      return a.d
    case 'line':
      return `M${num(a.x1)} ${num(a.y1)}L${num(a.x2)} ${num(a.y2)}`
    case 'circle': {
      const cx = num(a.cx), cy = num(a.cy), r = num(a.r)
      return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`
    }
    case 'ellipse': {
      const cx = num(a.cx), cy = num(a.cy), rx = num(a.rx), ry = num(a.ry)
      return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0`
    }
    case 'rect': {
      const x = num(a.x), y = num(a.y), w = num(a.width), h = num(a.height)
      const rx = num(a.rx, 0) || 0
      const ry = num(a.ry, rx)
      if (!rx && !ry) return `M${x} ${y}H${x + w}V${y + h}H${x}Z`
      return (
        `M${x + rx} ${y}H${x + w - rx}A${rx} ${ry} 0 0 1 ${x + w} ${y + ry}` +
        `V${y + h - ry}A${rx} ${ry} 0 0 1 ${x + w - rx} ${y + h}H${x + rx}` +
        `A${rx} ${ry} 0 0 1 ${x} ${y + h - ry}V${y + ry}A${rx} ${ry} 0 0 1 ${x + rx} ${y}Z`
      )
    }
    case 'polyline':
    case 'polygon': {
      const pts = String(a.points).trim().split(/[\s,]+/).map(Number)
      if (pts.length < 4) throw new Error(`bad ${tag} points: ${a.points}`)
      let d = `M${pts[0]} ${pts[1]}`
      for (let i = 2; i + 1 < pts.length; i += 2) d += `L${pts[i]} ${pts[i + 1]}`
      return tag === 'polygon' ? `${d}Z` : d
    }
    default:
      throw new Error(`unsupported lucide element <${tag}>`)
  }
}

const readIcon = (component) => {
  const file = join(lucideDir, 'dist', 'esm', 'icons', `${kebab(component)}.js`)
  const source = readFileSync(file, 'utf8')
  const start = source.indexOf('[', source.indexOf('['))
  const end = source.lastIndexOf(']);')
  const body = source.slice(start, end)
  const parts = []
  for (const m of body.matchAll(/\[\s*"(\w+)",\s*\{([^}]*)\}\s*\]/g)) {
    parts.push(toPath(m[1], attrMap(m[2])))
  }
  if (!parts.length) throw new Error(`no nodes in ${file}`)
  const name = /createLucideIcon\("([^"]+)"/.exec(source)?.[1]
  if (name !== kebab(component)) throw new Error(`${file}: expected ${kebab(component)}, got ${name}`)
  return parts.join('')
}

const escape = (s) => s.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;')

// --- emit ---------------------------------------------------------------------------------------------

const entries = []
const missing = []
for (const [key, component] of keys) {
  // `loader` is CoffeeSpinner, not a Lucide glyph: the app routes it to Controls/CoffeeSpinner.
  if (key === 'loader') continue
  if (!component) {
    missing.push(key)
    continue
  }
  entries.push([key, readIcon(component)])
}

const axaml = `<!-- GENERATED by tools/app/gen-icons.mjs — do not edit by hand.
     Source: lucide-vue-next ${lucidePkg.version} (dist/esm/icons), the same glyph data the web UI renders through
     SofiaIcon.vue. 24x24 viewBox, round caps/joins, stroke drawn at 1.75 by Controls/SofiaIcon.cs.
     ${entries.length} glyphs, keyed exactly like SofiaIcon.vue (the \`circle\` name is missing there too: the web
     renders nothing for it, so it stays missing here as well). -->
<ResourceDictionary xmlns="https://github.com/avaloniaui"
                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"
                    x:Class="Sofia.App.Theme.Icons">

${entries.map(([key, d]) => `  <StreamGeometry x:Key="Icon.${key}">${escape(d)}</StreamGeometry>`).join('\n')}

</ResourceDictionary>
`

writeFileSync(join(root, 'src', 'Sofia.App', 'Theme', 'Icons.axaml'), axaml, 'utf8')
console.log(`wrote ${entries.length} icons, lucide ${lucidePkg.version}${missing.length ? `, missing: ${missing.join(', ')}` : ''}`)

const MESSAGES: Record<Locale, Dict> = { en, pt, es, fr, zh, ja }

const FALLBACK: Locale = 'en'

const current = reactive<{ locale: Locale }>({ locale: 'en' })

/** Picks the UI language (also mirrored into settings by the caller). */
export function setLocale(locale: Locale): void {
  if (MESSAGES[locale]) current.locale = locale
}

export function useI18n() {
  /** Translates `key`, substituting `{name}` placeholders from `params`. */
  function t(key: string, params?: Record<string, string | number>): string {
    const text = MESSAGES[current.locale]?.[key] ?? MESSAGES[FALLBACK]?.[key] ?? key
    if (!params) return text
    return text.replace(/\{(\w+)\}/g, (whole, name: string) =>
      name in params ? String(params[name]) : whole,
    )
  }
  const locale = computed(() => current.locale)
  return { t, locale, setLocale }
}

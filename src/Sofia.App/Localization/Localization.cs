using System.Text;

namespace Sofia.App.I18n;

/// <summary>
/// The web's i18n layer (<c>src/Sofia.UI/src/i18n/index.ts</c>) ported to the native app: six locales, the same key
/// names and the same <c>{param}</c> interpolation, English as the fallback and the key itself when nothing matches.
/// </summary>
/// <remarks>
/// The six web dictionaries are generated into <c>Strings.Generated.cs</c> by
/// <c>.sofia/scripts/gen-i18n-043.cs</c>, so keys and values stay literally identical while both UIs exist.
/// <see cref="AppExtras"/> adds only the keys the web leaves hard-coded in English (header/panel/task copy, the
/// settings rows the Vue file writes inline, the LSP tab), translated here so the ported views never embed English.
/// </remarks>
public static class Localization
{
    /// <summary>Locale order of the web's <c>LANGUAGES</c> list.</summary>
    public static readonly string[] Languages = ["en", "pt", "es", "fr", "zh", "ja"];

    private static readonly Dictionary<string, Dictionary<string, string>> Table;

    private static string _current = "en";

    // A static constructor (not a field initializer) so AppExtras is assigned before BuildTable reads it.
    static Localization() => Table = BuildTable();

    /// <summary>Raised after the locale changed; views rebuild their labels.</summary>
    public static event Action? Changed;

    /// <summary>Active locale code (one of <see cref="Languages"/>).</summary>
    public static string Current => _current;

    /// <summary>Every key the app knows (English catalog, used by the coverage test).</summary>
    public static IReadOnlyCollection<string> Keys => Table["en"].Keys;

    public static void SetLocale(string? code)
    {
        var next = code is not null && Table.ContainsKey(code) ? code : "en";
        if (next == _current) return;
        _current = next;
        Changed?.Invoke();
    }

    /// <summary>Translates a key, falling back to English and then to the key itself.</summary>
    public static string T(string key)
    {
        if (Table[_current].TryGetValue(key, out var value)) return value;
        return Table["en"].TryGetValue(key, out var english) ? english : key;
    }

    /// <summary>Translates a key and substitutes the web's <c>{name}</c> placeholders.</summary>
    public static string T(string key, params (string Name, object? Value)[] args)
    {
        var text = T(key);
        if (args.Length == 0) return text;
        var values = new Dictionary<string, object?>(args.Length, StringComparer.Ordinal);
        foreach (var (name, value) in args) values[name] = value;
        return Format(text, values);
    }

    /// <summary>
    /// Same rule as the web's <c>t()</c>: only <c>{word}</c> placeholders with a supplied value are replaced; an
    /// unknown placeholder is left visible instead of throwing.
    /// </summary>
    public static string Format(string text, IReadOnlyDictionary<string, object?> values)
    {
        if (text.IndexOf('{') < 0) return text;
        var builder = new StringBuilder(text.Length + 16);
        for (var i = 0; i < text.Length; i++)
        {
            var ch = text[i];
            if (ch != '{')
            {
                builder.Append(ch);
                continue;
            }

            var end = text.IndexOf('}', i + 1);
            if (end < 0)
            {
                builder.Append(text, i, text.Length - i);
                break;
            }

            var name = text.Substring(i + 1, end - i - 1);
            if (IsWord(name) && values.TryGetValue(name, out var value))
            {
                builder.Append(value?.ToString() ?? "");
                i = end;
                continue;
            }

            builder.Append(ch);
        }
        return builder.ToString();
    }

    /// <summary>Human label of a locale code (the web's <c>LANGUAGES[].label</c>).</summary>
    public static string LanguageLabel(string code) => code switch
    {
        "pt" => "Português",
        "es" => "Español",
        "fr" => "Français",
        "zh" => "中文",
        "ja" => "日本語",
        _ => "English",
    };

    private static bool IsWord(string value)
    {
        if (value.Length == 0) return false;
        foreach (var ch in value)
        {
            if (!char.IsLetterOrDigit(ch) && ch != '_') return false;
        }
        return true;
    }

    private static Dictionary<string, Dictionary<string, string>> BuildTable()
    {
        var table = new Dictionary<string, Dictionary<string, string>>(StringComparer.Ordinal);
        foreach (var code in Languages)
        {
            table[code] = LocalizedCatalog.All.TryGetValue(code, out var web)
                ? new Dictionary<string, string>(web, StringComparer.Ordinal)
                : new Dictionary<string, string>(StringComparer.Ordinal);
        }

        // App-only keys: they fill the gaps the web leaves hard-coded and never override a web key.
        foreach (var (code, extras) in AppExtras)
        {
            var target = table[code];
            foreach (var (key, value) in extras)
                if (!target.ContainsKey(key)) target[key] = value;
        }
        return table;
    }


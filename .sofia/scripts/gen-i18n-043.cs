// Spec 043: converts the Vue i18n catalog (six locales, {param} interpolation) into the C# resource table the
// Avalonia app ships. The web file is the source of truth: keys and values are copied verbatim, so both UIs stay
// interchangeable while they coexist. Run: dotnet run .sofia/scripts/gen-i18n-043.cs
using System.Globalization;
using System.Text;

var root = FindRepoRoot();
var source = Path.Combine(root, "src", "Sofia.UI", "src", "i18n", "index.ts");
var target = Path.Combine(root, "src", "Sofia.App", "Localization", "Strings.Generated.cs");
var text = File.ReadAllText(source, Encoding.UTF8);
var lines = text.Replace("\r\n", "\n").Split('\n');

var locales = new List<(string Code, List<(string Key, string Value)> Entries)>();
string? current = null;
List<(string, string)>? entries = null;
string? pendingKey = null;

foreach (var raw in lines)
{
    var line = raw;
    var header = System.Text.RegularExpressions.Regex.Match(line, @"^const (\w+): Dict = \{");
    if (header.Success)
    {
        current = header.Groups[1].Value;
        entries = [];
        pendingKey = null;
        continue;
    }
    if (current is null || entries is null) continue;
    if (line.TrimStart().StartsWith("}"))
    {
        locales.Add((current, entries));
        current = null;
        entries = null;
        pendingKey = null;
        continue;
    }

    var trimmed = line.Trim();
    if (pendingKey is not null)
    {
        if (TryReadLiteral(trimmed, out var continued))
        {
            entries.Add((pendingKey, continued));
            pendingKey = null;
        }
        continue;
    }

    var match = System.Text.RegularExpressions.Regex.Match(trimmed, @"^'(?<key>(?:[^'\\]|\\.)*)'\s*:\s*(?<rest>.*)$");
    if (!match.Success) continue;
    var key = Unescape(match.Groups["key"].Value);
    var rest = match.Groups["rest"].Value.Trim();
    if (rest.Length == 0)
    {
        pendingKey = key;
        continue;
    }
    if (TryReadLiteral(rest, out var value)) entries.Add((key, value));
}

if (locales.Count != 6)
{
    Console.Error.WriteLine($"expected 6 locales, parsed {locales.Count}");
    return 1;
}

var sb = new StringBuilder();
sb.AppendLine("// <auto-generated>");
sb.AppendLine("// Generated by .sofia/scripts/gen-i18n-043.cs from src/Sofia.UI/src/i18n/index.ts.");
sb.AppendLine("// Do not edit by hand: change the Vue catalog (or the script) and regenerate.");
sb.AppendLine("// </auto-generated>");
sb.AppendLine("namespace Sofia.App.I18n;");
sb.AppendLine();
sb.AppendLine("/// <summary>The web's six locale dictionaries, key for key (en, pt, es, fr, zh, ja).</summary>");
sb.AppendLine("internal static class LocalizedCatalog");
sb.AppendLine("{");
sb.AppendLine("    public static readonly IReadOnlyDictionary<string, Dictionary<string, string>> All =");
sb.AppendLine("        new Dictionary<string, Dictionary<string, string>>(StringComparer.Ordinal)");
sb.AppendLine("        {");
foreach (var (code, list) in locales)
{
    sb.AppendLine($"            [\"{code}\"] = new Dictionary<string, string>(StringComparer.Ordinal)");
    sb.AppendLine("            {");
    foreach (var (key, value) in list)
        sb.AppendLine($"                [\"{Escape(key)}\"] = \"{Escape(value)}\",");
    sb.AppendLine("            },");
}
sb.AppendLine("        };");
sb.AppendLine("}");
Directory.CreateDirectory(Path.GetDirectoryName(target)!);
File.WriteAllText(target, sb.ToString(), new UTF8Encoding(false));
foreach (var (code, list) in locales) Console.WriteLine($"{code}: {list.Count} keys");
Console.WriteLine($"wrote {target}");
return 0;

static bool TryReadLiteral(string text, out string value)
{
    value = string.Empty;
    if (text.Length == 0 || text[0] != '\'') return false;
    var builder = new StringBuilder();
    for (var i = 1; i < text.Length; i++)
    {
        var ch = text[i];
        if (ch == '\\' && i + 1 < text.Length)
        {
            var next = text[++i];
            builder.Append(next switch
            {
                'n' => '\n',
                't' => '\t',
                'r' => '\r',
                _ => next,
            });
            continue;
        }
        if (ch == '\'') { value = builder.ToString(); return true; }
        builder.Append(ch);
    }
    return false;
}

static string Unescape(string text) => text.Replace("\\'", "'").Replace("\\\\", "\\");

static string Escape(string text) => text
    .Replace("\\", "\\\\")
    .Replace("\"", "\\\"")
    .Replace("\n", "\\n")
    .Replace("\r", "\\r")
    .Replace("\t", "\\t");

static string FindRepoRoot()
{
    var dir = new DirectoryInfo(AppContext.BaseDirectory);
    while (dir is not null)
    {
        if (File.Exists(Path.Combine(dir.FullName, "Sofia.slnx"))) return dir.FullName;
        dir = dir.Parent;
    }
    return Directory.GetCurrentDirectory();
}
